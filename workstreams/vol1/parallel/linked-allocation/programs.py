def with_cycles():
    result=[]
    for row in TOPO[:-2]:
        result.append(row)
        if row==('TAPEOUT','EQU','2'):
            result.append(('PRINTER','EQU','18'))
        if row==('1H','LD6','BUFFER+1'):
            result.append(('','ST6','NO'))
        if row==('','LD2','X,1(TOP)'):
            result.append(('','STZ','X,1(TOP)'))
    return result+CYCLE_END

