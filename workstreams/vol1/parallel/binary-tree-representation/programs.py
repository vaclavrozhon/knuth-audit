def assemble(b=64,repair_comparisons=False,extra=(),redirect=()):
    numbered=[(n,(l,o,x.ljust(5) if o=='ALF' else x)) for n,l,o,x in (s.split('|') for s in TEXT.strip().splitlines())]
    if repair_comparisons:
        replacements={'197':('CMPA','CON1+1'),'198':('JNE','1F'),
                      '202':('CMPA','CON1+1'),'203':('JNE','1F'),
                      '252':('CMPA','CON2+1'),'253':('JE','3F'),'254':('DECA','1')}
        numbered=[(n,(l,*replacements[n]) if n in replacements else (l,o,x)) for n,(l,o,x) in numbered]
    redirect=dict(redirect)
    numbered=[(n,(l,'JSJ',redirect[l]) if l in redirect else (l,o,x)) for n,(l,o,x) in numbered]
    prefix=[('Y','EQU','20'),('DY','EQU','22'),('AVAIL','EQU','24'),('','ORIG','100')]
    rows=prefix+[row for n,row in numbered]+list(extra)+[('OVERFLOW','HLT',''),('','END','D1')]
    a=Assembly(rows,b)
    a.line_addresses={n:a.locations[len(prefix)+i] for i,(n,_) in enumerate(numbered)}
    a.audit_rows=rows
    return a


if __name__=='__main__':
    import json
    out=Path(__file__).resolve().parent/'results'
    for b in [64,100]:
        a=assemble(b)
        (out/f'book-{b}.json').write_text(json.dumps({'line_addresses':a.line_addresses,'symbols':{s:w.value(b) for s,w in a.symbols.items()},'words':{str(p):[w.sign,*w.digits] for p,w in a.memory.items()}},indent=2)+'\n')
    (out/'book-complete.mixal').write_text('\n'.join(f'{l:12} {o:7} {x}' for l,o,x in a.audit_rows)+'\n')
    print('Full differentiator assembled; highest program address',max(a.memory))
